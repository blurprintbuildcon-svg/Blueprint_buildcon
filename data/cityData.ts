export function getCityBySlug(slug: string): CityDetail {
  const normalized = slug.toLowerCase().trim().replace(/\s+/g, '-');
  if (CITIES_DATA[normalized]) {
    return CITIES_DATA[normalized];
  }
  // Try matching by name
  for (const city of Object.values(CITIES_DATA)) {
    if (city.name.toLowerCase() === slug.toLowerCase()) {
      return city;
    }
  }
  // Default to Hyderabad if not matched
  return CITIES_DATA['hyderabad'];
}

